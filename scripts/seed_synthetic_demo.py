"""Seed one synthetic claim with real image/document files for the live UI demo.

The tabular row comes from the de-identified public golden research case. The
vehicle photo is AI-generated; the estimate and graph are synthetic. The
seeded runtime claim is ignored by Git and cannot be mistaken for real data.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

CLAIM_ID = "CLM-DEMO-SYN-001"
SEED_MARKER = ROOT / "runtime/claims" / CLAIM_ID / "demo_seed.json"


def main() -> None:
    from scripts.build_synthetic_demo_document import build as build_document

    photo = ROOT / "prototype/demo_assets/synthetic_vehicle_collision.png"
    if not photo.is_file():
        raise FileNotFoundError(f"Synthetic demo photo is missing: {photo}")
    document = build_document()
    source = ROOT / "data/golden/claims/CLM-GOLD-001"
    golden = json.loads((source / "claim.json").read_text(encoding="utf-8"))

    os.environ["INSURANCE_API_MODE"] = "live"
    from fastapi.testclient import TestClient
    from src.api.app import app

    claim_root = SEED_MARKER.parent
    if claim_root.exists() and not SEED_MARKER.is_file():
        raise FileExistsError(f"Existing claim has no synthetic-demo marker; refusing to change it: {claim_root}")

    with TestClient(app) as client:
        if not SEED_MARKER.is_file():
            intake = {
                "claim_amount": golden["claim_amount"],
                "incident_date": golden["incident_date"],
                "plate_number": golden["plate_number"],
                "tabular_features": golden["tabular_features"],
                "required_evidence": ["claim-intake", "vehicle_image", "claim_document", "relationship-graph"],
            }
            response = client.post(f"/claims/{CLAIM_ID}/intake", json=intake)
            response.raise_for_status()
            for kind, asset in (("image", photo), ("document", document)):
                with asset.open("rb") as stream:
                    response = client.post(
                        f"/claims/{CLAIM_ID}/evidence", data={"kind": kind},
                        files={"file": (asset.name, stream, "image/png")},
                    )
                response.raise_for_status()

            # A synthetic point-in-time graph uses the same claim ID as the
            # intake, image and document. No production entity is included.
            graph = json.loads((source / "entities.json").read_text(encoding="utf-8"))
            encoded = json.dumps(graph).replace("CLM-GOLD-001", CLAIM_ID)
            (claim_root / "entities.json").write_text(json.dumps(json.loads(encoded), indent=2) + "\n", encoding="utf-8")
            fields = {
                "claim_id": CLAIM_ID,
                "document_id": "EST-DEMO-001",
                "evidence_id": "demo-precomputed-fields",
                "document_type": "synthetic_repair_estimate",
                "source": "synthetic_precomputed_demo_fields_not_model_output",
                "fields": [
                    {"field_name": "total_amount", "raw_text": "61,620", "normalized_value": 61620, "confidence": 1.0},
                    {"field_name": "document_date", "raw_text": golden["incident_date"], "normalized_value": golden["incident_date"], "confidence": 1.0},
                    {"field_name": "plate_number", "raw_text": golden["plate_number"], "normalized_value": golden["plate_number"], "confidence": 1.0},
                ],
            }
            (claim_root / "documents" / "synthetic_fields.json").write_text(json.dumps(fields, indent=2) + "\n", encoding="utf-8")
            SEED_MARKER.write_text(json.dumps({
                "claim_id": CLAIM_ID,
                "demo_only": True,
                "photo_source": "AI-generated by built-in imagegen for this demo",
                "document_source": "deterministic synthetic sample",
                "tabular_source": "de-identified public research golden row CLM-GOLD-001",
                "graph_source": "synthetic point-in-time relationships",
                "precomputed_fields_are_model_output": False,
            }, indent=2) + "\n", encoding="utf-8")

        response = client.post(f"/claims/{CLAIM_ID}/analyze", json={})
        response.raise_for_status()
        analysis = response.json()
        summary = {
            "claim_id": CLAIM_ID,
            "analysis_status": analysis["analysis_status"],
            "priority": analysis["priority"],
            "research_risk_score": analysis["research_risk_score"],
            "evidence_count": len(analysis["evidence"]),
            "signal_count": len(analysis["signals"]),
            "module_status": analysis["module_status"],
            "url": f"http://127.0.0.1:8000/?claim_id={CLAIM_ID}",
        }
        if not any(row["kind"] == "image" for row in analysis["evidence"]):
            raise RuntimeError("Demo image did not reach claim analysis.")
        if not any(row["kind"] == "document" for row in analysis["evidence"]):
            raise RuntimeError("Demo document did not reach claim analysis.")
        output = ROOT / "runtime/synthetic_demo_smoke.json"
        output.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
